'use strict';

// Regenerates js/base-parts.js by inlining the shared DOCX package parts, so the
// phone app is self-contained and needs no network access to build a document.
// Run with: node tools/build-base-parts.js

const fs = require('fs');
const path = require('path');

const SOURCE = path.join(__dirname, '..', '..', 'decree-generator', 'assets', 'base');
const TARGET = path.join(__dirname, '..', 'js', 'base-parts.js');

function collect(dir, prefix = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...collect(path.join(dir, entry.name), rel));
    else out.push({ rel, abs: path.join(dir, entry.name) });
  }
  return out;
}

if (!fs.existsSync(SOURCE)) {
  console.error(`Cannot find the base package parts at ${SOURCE}`);
  process.exit(1);
}

const files = collect(SOURCE).sort((a, b) => a.rel.localeCompare(b.rel));
const entries = files.map(
  (file) => `  ${JSON.stringify(file.rel)}: ${JSON.stringify(fs.readFileSync(file.abs, 'utf8'))},`
);

const output =
  '// Generated by tools/build-base-parts.js - do not edit by hand.\n' +
  '// Shared DOCX package parts (styles, fonts, theme, page setup) taken from the\n' +
  '// reference decrees, so generated files keep exactly the same formatting.\n\n' +
  'export const BASE_PARTS = {\n' +
  entries.join('\n') +
  '\n};\n';

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, output, 'utf8');

const kb = (Buffer.byteLength(output) / 1024).toFixed(1);
console.log(`Wrote ${files.length} parts to ${TARGET} (${kb} KB)`);
