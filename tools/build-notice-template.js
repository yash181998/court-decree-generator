'use strict';

// Regenerates js/notice-template.js by inlining the two-column notice template
// as base64, so the phone app carries it with no network access.
// Run with: node tools/build-notice-template.js

const fs = require('fs');
const path = require('path');

const SOURCE =
  process.env.NOTICE_TEMPLATE ||
  path.join(__dirname, '..', '..', 'Autofill details in format', 'Notice format in 2 Columns.docx');
const TARGET = path.join(__dirname, '..', 'js', 'notice-template.js');

if (!fs.existsSync(SOURCE)) {
  console.error(`Cannot find the notice template at ${SOURCE}`);
  console.error('Set NOTICE_TEMPLATE to its full path and run again.');
  process.exit(1);
}

const base64 = fs.readFileSync(SOURCE).toString('base64');

// Wrapped so the generated file stays readable in an editor and diffs sanely.
const wrapped = (base64.match(/.{1,120}/g) || []).map((line) => `  '${line}'`).join(' +\n');

const output =
  '// Generated by tools/build-notice-template.js - do not edit by hand.\n' +
  '// The original "Notice format in 2 Columns.docx", base64 encoded. Only its\n' +
  '// <w:body> is replaced at generation time, so every style and theme survives.\n\n' +
  'export const NOTICE_TEMPLATE_BASE64 =\n' +
  wrapped +
  ';\n';

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, output, 'utf8');

console.log(
  `Wrote ${path.basename(SOURCE)} (${(fs.statSync(SOURCE).size / 1024).toFixed(1)} KB) ` +
    `to ${TARGET} (${(Buffer.byteLength(output) / 1024).toFixed(1)} KB)`
);
